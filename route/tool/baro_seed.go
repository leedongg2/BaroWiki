// baro_seed_documents : 기본 문서 심기 (한 번만)
func baro_seed_documents(db *sql.DB) {
	done := ""
	if QueryRow_DB(db, "select name from baro_set where name = 'seed_document'", []any{&done}) {
		return
	}

	for _, row := range baro_seed_list() {
		title := row[0]
		data := row[1]

		exist := ""
		if QueryRow_DB(db, "select title from data where title = ?", []any{&exist}, title) {
			continue
		}

		Exec_DB(db, "insert into data (title, data, type) values (?, ?, '')", title, data)
		Do_add_history(
			db, title, data, Get_time(), "system", "바로위키 기본 문서",
			"+"+Baro_itoa(Get_len(data)), "", "",
		)
	}

	Baro_put(db, "seed_document", "on")
}
